# tests/test_gerrit.py

import pytest
from helpers import FakeWeb, ok

from depdelta_cli import gerrit, web
from depdelta_cli.env import GerritChange

CHANGE = GerritChange("https://gerrit.test", "web~12", "abc")


def test_post_success(monkeypatch):
    fake = FakeWeb(ok({"labels": {}}))
    monkeypatch.setattr(web, "request", fake)

    gerrit.post(CHANGE, "DepDelta review", "bot", "pw")

    assert fake.calls == [
        {
            "method": "POST",
            "url": "https://gerrit.test/a/changes/web~12/revisions/abc/review",
            "body": {
                "message": "DepDelta review",
                "tag": "autogenerated:depdelta",
                "notify": "OWNER",
            },
            "headers": {"Authorization": web.basic("bot", "pw")},
        }
    ]


def test_post_refused(monkeypatch):
    monkeypatch.setattr(web, "request", FakeWeb(ok("Unauthorized", 401)))

    with pytest.raises(gerrit.GerritError, match="Gerrit answered 401: Unauthorized"):
        gerrit.post(CHANGE, "m", "bot", "pw")


def test_post_refused_without_text(monkeypatch):
    monkeypatch.setattr(web, "request", FakeWeb(ok({"x": 1}, 500)))

    with pytest.raises(gerrit.GerritError, match=r"^Gerrit answered 500:$"):
        gerrit.post(CHANGE, "m", "bot", "pw")


def test_fit_short_message_unchanged():
    assert gerrit.fit("short", "https://x") == "short"


def test_fit_cuts_with_the_link(monkeypatch):
    monkeypatch.setattr(gerrit, "MAX_MESSAGE", 60)

    cut = gerrit.fit("a" * 100, "https://d.test/x")

    assert len(cut) <= 60
    assert cut.endswith("… cut to fit. The full review: https://d.test/x")


def test_fit_cuts_without_a_link(monkeypatch):
    monkeypatch.setattr(gerrit, "MAX_MESSAGE", 10)

    assert gerrit.fit("a" * 100) == "a" * 7 + "\n\n…"
